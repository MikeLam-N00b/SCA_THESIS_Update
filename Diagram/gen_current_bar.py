# ─── Compute mean ± std per phase ─────────────────────────────────────────────
def stats(raw, classify):
    buckets = {"idle": [], "sim": [], "uwb": []}
    for t, I in raw:
        phase = classify(t)
        if phase:
            buckets[phase].append(I)
    return {k: (np.mean(v), np.std(v), len(v)) for k, v in buckets.items()}

